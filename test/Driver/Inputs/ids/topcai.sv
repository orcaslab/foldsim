// 120 producers in a chain, 120 consumers: consumer i reads producer src(i),
// in two runs of parents (6 of 10, then 10 of 6) whose children's sources step
// by a slope that depends on the child: the consumers' address table (by
// instance) is column-affine.
module Prod(input logic clk, reset, input logic [15:0] id, input logic [7:0] d, output logic [7:0] q);
  logic [7:0] r;
  always_ff @(posedge clk) r <= reset ? id[7:0] : (d ^ r) + id[15:8];
  assign q = r;
endmodule
module Cons(input logic clk, reset, input logic [7:0] a, output logic [7:0] q);
  logic [7:0] r;
  always_ff @(posedge clk) r <= reset ? 8'd0 : {r[6:0], r[7]} + a;
  assign q = r;
endmodule
