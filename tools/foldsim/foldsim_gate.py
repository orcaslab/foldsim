#!/usr/bin/env python3
"""A cycle-exactness gate for any design: its RTL against its simulator.

Writes two Verilator testbenches from a generation's foldsim_sim.json, the
design itself known only by its top's ports:

  gate_ref.sv  `gate_ref`: the unfolded top, one target cycle per clock, its
               inputs each cycle a line of the stimulus file (+stim=<file>, hex:
               the inputs concatenated in the order of foldsim_sim.json),
               its outputs each cycle written as a line to +trace=<file>.
  gate_sim.sv  `gate_sim`: the simulator (foldsim_sim) on the same tokens,
               each input channel offered its next token and each output
               channel ready on all but +stall=<percent> of the host cycles
               (and `advance` low on +bubble=<percent>, with --bubbles), its
               output tokens written in the same format; it prints the host
               cycles taken (H = host cycles per target cycle).

The traces of a cycle-exact simulator are identical (`compare`). The stimulus
holds +cycles=<T> lines; `ports` prints the input layout for a stimulus
writer, and `stim` writes a random one (each input uniform, a reset input
held for its first cycles).

usage: foldsim_gate.py tb --sim-json <foldsim_sim.json> --clock <port> --out <dir>
       foldsim_gate.py ports --sim-json <foldsim_sim.json> [--clock <port>]
       foldsim_gate.py stim <out.hex> --sim-json <foldsim_sim.json> --cycles T [--seed S]
                       [--reset NAME:N[:low]]
       foldsim_gate.py compare <ref trace> <sim trace> --sim-json <foldsim_sim.json> [--skip N]
"""
import argparse
import json
import sys


def channels(sim_json):
    """(inputs, outputs, has_advance): [(name, width)] of the target's ports
    as the simulator's channels carry them, in foldsim_sim.json's order."""
    ports = json.load(open(sim_json))['ports']
    width = {p['name']: p['width'] for p in ports}
    ins, outs = [], []
    for p in ports:
        n = p['name']
        if n.endswith('_valid') and n[:-6] + '_ready' in width and n[:-6] + '_bits' in width:
            (ins if p['dir'] == 'in' else outs).append((n[:-6], width[n[:-6] + '_bits']))
    return ins, outs, 'advance' in width


def bits(ws):
    return sum(w for _, w in ws)


def slices(ws):
    """name -> (msb, lsb) of each port in the packed line, the first port at the top."""
    out, hi = {}, bits(ws)
    for n, w in ws:
        out[n] = (hi - 1, hi - w)
        hi -= w
    return out


def ref_tb(top, clock, ins, outs, maxt):
    iw, ow = max(bits(ins), 1), max(bits(outs), 1)
    si, so = slices(ins), slices(outs)
    conns = [f'.{clock}(clk)'] + [f'.{n}(stim[t][{si[n][0]}:{si[n][1]}])' for n, _ in ins] + \
            [f'.{n}(o_{n})' for n, _ in outs]
    decl = ''.join(f'  wire [{w - 1}:0] o_{n};\n' for n, w in outs)
    cat = ', '.join(f'o_{n}' for n, _ in outs) or "1'b0"
    return f'''// Generated by foldsim_gate.py: the unfolded {top}, one target cycle per clock.
`timescale 1ns / 1ps
module gate_ref;
  localparam IW = {iw}, OW = {ow}, MAXT = {maxt};
  int T = 0, t = 0, fd;
  string stim_f, trace_f;
  logic [IW-1:0] stim [MAXT];
  logic clk = 0;
{decl}  {top} dut({', '.join(conns)});
  initial begin
    if (!$value$plusargs("cycles=%d", T)) $fatal(1, "+cycles=<T>");
    if (!$value$plusargs("stim=%s", stim_f)) $fatal(1, "+stim=<file>");
    if (!$value$plusargs("trace=%s", trace_f)) $fatal(1, "+trace=<file>");
    if (T > MAXT) $fatal(1, "+cycles over %0d (foldsim_gate.py --max-cycles)", MAXT);
    $readmemh(stim_f, stim, 0, T - 1);
    fd = $fopen(trace_f, "w");
    for (t = 0; t < T; t++) begin
      #1; $fwrite(fd, "%h\\n", {{{cat}}});
      clk = 1; #1; clk = 0;
    end
    $fclose(fd);
    $display("REF %0d cycles", T);
    $finish;
  end
endmodule
'''


def sim_tb(ins, outs, advance, maxt):
    iw, ow = max(bits(ins), 1), max(bits(outs), 1)
    si, so = slices(ins), slices(outs)
    L = []
    L.append(f'''// Generated by foldsim_gate.py: the simulator on the same tokens, channels stalled at random.
`timescale 1ns / 1ps
module gate_sim;
  localparam IW = {iw}, OW = {ow}, MAXT = {maxt};
  int T = 0, fd, stall = 0, bubble = 0, cyc = 0, maxcyc = 0;
  string stim_f, trace_f;
  logic [IW-1:0] stim [MAXT];
  logic [OW-1:0] got [MAXT];
  logic clk = 0, rst = 1, adv;
  always #5 clk = ~clk;
''')
    for n, w in ins:
        L.append(f'  int i_{n} = 0; logic v_{n}; wire r_{n};\n')
    for n, w in outs:
        L.append(f'  int k_{n} = 0; logic r_{n}; wire v_{n}; wire [{w - 1}:0] b_{n};\n')
    conns = ['.hostClock(clk)', '.hostReset(rst)']
    for n, w in ins:
        idx = f'(i_{n} < T ? i_{n} : 0)'
        conns += [f'.{n}_valid(v_{n})', f'.{n}_bits(stim[{idx}][{si[n][0]}:{si[n][1]}])', f'.{n}_ready(r_{n})']
    for n, w in outs:
        conns += [f'.{n}_valid(v_{n})', f'.{n}_bits(b_{n})', f'.{n}_ready(r_{n})']
    if advance:
        conns.append('.advance(adv)')
    conns.append('.profile_finish()')
    L.append('  foldsim_sim dut(' + ',\n    '.join(conns) + ');\n')
    L.append('''  initial begin
    if (!$value$plusargs("cycles=%d", T)) $fatal(1, "+cycles=<T>");
    if (!$value$plusargs("stim=%s", stim_f)) $fatal(1, "+stim=<file>");
    if (!$value$plusargs("trace=%s", trace_f)) $fatal(1, "+trace=<file>");
    if (!$value$plusargs("stall=%d", stall)) stall = 0;
    if (!$value$plusargs("bubble=%d", bubble)) bubble = 0;
    if (!$value$plusargs("maxcyc=%d", maxcyc)) maxcyc = T * 4096 + 100000;
    if (T > MAXT) $fatal(1, "+cycles over %0d (foldsim_gate.py --max-cycles)", MAXT);
    $readmemh(stim_f, stim, 0, T - 1);
  end
  always @(negedge clk) begin
''')
    for n, _ in ins:
        L.append(f'    v_{n} = i_{n} < T && ($urandom % 100 >= stall);\n')
    for n, _ in outs:
        L.append(f'    r_{n} = $urandom % 100 >= stall;\n')
    L.append('    adv = $urandom % 100 >= bubble;\n  end\n')
    L.append('  always @(posedge clk) begin\n    cyc <= cyc + 1; rst <= 0;\n    if (!rst) begin\n')
    for n, _ in ins:
        L.append(f'      if (v_{n} && r_{n}) i_{n} <= i_{n} + 1;\n')
    for n, _ in outs:
        L.append(f'      if (v_{n} && r_{n} && k_{n} < T) begin got[k_{n}][{so[n][0]}:{so[n][1]}] <= b_{n}; '
                 f'k_{n} <= k_{n} + 1; end\n')
    L.append('    end\n  end\n')
    done = ' && '.join(f'k_{n} >= T' for n, _ in outs) or '1'
    L.append(f'''  initial begin
    @(negedge rst);
    do @(posedge clk); while (!({done}) && cyc < maxcyc);
    @(posedge clk);
    if (!({done})) begin $display("TIMEOUT after %0d host cycles", cyc); $finish; end
    fd = $fopen(trace_f, "w");
    for (int t = 0; t < T; t++) $fwrite(fd, "%h\\n", got[t]);
    $fclose(fd);
    $display("SIM %0d cycles in %0d host cycles, H %0.2f", T, cyc, real'(cyc) / T);
    $finish;
  end
endmodule
''')
    return ''.join(L)


def compare(ref, sim, outs, skip):
    so = slices(outs)
    a, b = open(ref).read().split(), open(sim).read().split()
    if len(a) != len(b):
        print(f'MISMATCH: {len(a)} reference cycles, {len(b)} simulated')
        return 1
    for t, (x, y) in enumerate(zip(a, b)):
        if t >= skip and x.lower() != y.lower():
            xi, yi = int(x, 16), int(y, 16)
            diff = [n for n, (hi, lo) in so.items()
                    if (xi >> lo) & ((1 << (hi - lo + 1)) - 1) != (yi >> lo) & ((1 << (hi - lo + 1)) - 1)]
            print(f'MISMATCH cycle {t}: {", ".join(diff)} (ref {x}, sim {y})')
            return 1
    print(f'MATCH {len(a) - skip} cycles')
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('what', choices=('tb', 'ports', 'stim', 'compare'))
    ap.add_argument('files', nargs='*')
    ap.add_argument('--sim-json', required=True)
    ap.add_argument('--clock', default='clk')
    ap.add_argument('--out', default='.')
    ap.add_argument('--skip', type=int, default=0)
    ap.add_argument('--cycles', type=int, default=0)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--reset', action='append', default=[], metavar='NAME:N[:low]',
                    help='stim: the input NAME active (1, or 0 with :low) for the first N cycles, '
                         'inactive after')
    ap.add_argument('--max-cycles', type=int, default=1 << 20, help='the most target cycles a run takes')
    a = ap.parse_args()
    ins, outs, adv = channels(a.sim_json)
    if a.what == 'ports':
        for n, (hi, lo) in slices(ins).items():
            print(n, hi, lo)
        return 0
    if a.what == 'stim':
        import random
        rnd = random.Random(a.seed)
        sl, w = slices(ins), max(bits(ins), 1)
        resets = {}
        for r in a.reset:
            f = r.split(':')
            if f[0] not in sl or len(f) not in (2, 3) or (len(f) == 3 and f[2] != 'low'):
                sys.exit(f'--reset {r}: not NAME:N[:low] of an input')
            resets[f[0]] = (int(f[1]), len(f) == 3)
        with open(a.files[0], 'w') as f:
            for t in range(a.cycles):
                v = 0
                for n, (hi, lo) in sl.items():
                    if n in resets:
                        x = int((t < resets[n][0]) != resets[n][1])
                    else:
                        x = rnd.getrandbits(hi - lo + 1)
                    v |= x << lo
                f.write('%0*x\n' % ((w + 3) // 4, v))
        return 0
    if a.what == 'compare':
        if len(a.files) != 2:
            sys.exit('compare <ref trace> <sim trace>')
        return compare(*a.files, outs, a.skip)
    top = json.load(open(a.sim_json))['top']
    import os
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, 'gate_ref.sv'), 'w').write(ref_tb(top, a.clock, ins, outs, a.max_cycles))
    open(os.path.join(a.out, 'gate_sim.sv'), 'w').write(sim_tb(ins, outs, adv, a.max_cycles))
    return 0


if __name__ == '__main__':
    sys.exit(main())
