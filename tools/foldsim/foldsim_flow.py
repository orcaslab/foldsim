#!/usr/bin/env python3
"""The design-independent steps of a foldsim image flow, from a target manifest.

  lift       flow/lift_boundaries.py on the design's sources with the
             manifest's [lift] units: the units given plain-port boundaries
             (a module with interface ports becomes a class). Writes
             <out>/srcs.f, the driver's source list.
  kernel-vh  the kernel shell's header for the generated simulator: its
             memory ports, their channel shift and AXI id width, the
             port-repeat macros (8 ports a line: Verilator takes at most
             40000 tokens on a line) and the AXI speculation depth, from the
             manifest's [platform] (mem_ports, mem_channel_shift,
             mem_id_width) and axi_spec; then the virtual memories' masters,
             from the kernel's vmem_ports.py (it is versioned with the kernel
             RTL) on <gen>/foldsim_sim.vh.

The design's own steps (generating its sources: Vortex's gen_sources.sh with
its CONFIGS) stay the design's; everything here reads only the manifest.

usage: foldsim_flow.py lift --manifest <m> --srcs <srcs.f> --out <dir> [--python <pyslang python>]
       foldsim_flow.py kernel-vh --manifest <m> --sim-vh <foldsim_sim.vh> --vmem-ports <vmem_ports.py>
                       [--cache-rows N] [--vmem-masters N] [--var VAR=VALUE ...]
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import foldsim_manifest as fm  # noqa: E402

HERE = os.path.dirname(os.path.realpath(__file__))
BANNER = '// Generated by foldsim_flow.py kernel-vh. Do not edit.'


def mem_repeat(q, ports):
    """FOLDSIM_MEM_REPEAT<q>(f,s): `f(p) for ports 8q..8q+7, joined by `s, a
    part after the first led by `s unless it is empty."""
    xs = ['`f(%d)' % p for p in range(8 * q, min(8 * q + 8, ports))]
    return ('`s ' if q and xs else '') + ' `s '.join(xs)


def kernel_vh(a):
    get = lambda k: fm.get(a.manifest, k, a.var)
    ports = get('platform.mem_ports')
    if ports not in (1, 2, 4, 8, 16, 32):
        sys.exit(f'kernel-vh: [platform] mem_ports {ports}: the kernel has 1, 2, 4, 8, 16 or 32 memory ports')
    id_w = get('platform.mem_id_width')
    if id_w is None:
        sys.exit('kernel-vh: [platform] mem_id_width is the AXI id width of the target\'s memory ports')
    shift = get('platform.mem_channel_shift') or 0
    spec = next((v for v in (get(f'{s}.axi_spec') for s in ('platform', 'options', 'memory')) if v), 0)
    lines = [a.banner, f'`define FOLDSIM_MEM_PORTS {ports}', f'`define FOLDSIM_MEM_CH_SHIFT {shift}',
             f'`define FOLDSIM_MEM_ID_W {id_w}']
    lines += [f'`define FOLDSIM_MEM_REPEAT{q}(f,s) {mem_repeat(q, ports)}' for q in range(4)]
    if spec:
        lines.append(f'`define FOLDSIM_MEM_SPEC {spec}')
    cmd = [sys.executable, a.vmem_ports, '--sim-vh', a.sim_vh, '--mem-ports', str(ports)]
    if a.cache_rows:
        cmd += ['--cache-rows', a.cache_rows]
    if a.vmem_masters:
        cmd += ['--vmem-masters', a.vmem_masters]
    vmem = subprocess.run(cmd, check=True, text=True, capture_output=True).stdout
    sys.stdout.write('\n'.join(lines) + '\n' + vmem)


def lift(a):
    units = fm.get(a.manifest, 'lift.units', a.var) or []
    top = fm.get(a.manifest, 'design.top', a.var)
    steps = fm.get(a.manifest, 'rtl.max_generate_steps', a.var)
    if not top:
        sys.exit('lift: no [design] top in the manifest')
    cmd = [a.python, os.path.join(HERE, 'flow', 'lift_boundaries.py'), '--srcs', a.srcs, '--top', top,
           '--out', a.out] + [x for u in units for x in ('--unit', u)]
    if steps:
        cmd += ['--max-generate-steps', str(steps)]
    print('+', ' '.join(cmd), file=sys.stderr)
    sys.exit(subprocess.run(cmd).returncode)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('what', choices=('lift', 'kernel-vh'))
    ap.add_argument('--manifest', required=True)
    ap.add_argument('--var', action='append', default=[], metavar='VAR=VALUE')
    ap.add_argument('--srcs')
    ap.add_argument('--out')
    ap.add_argument('--python', default=sys.executable, help='lift: a Python with pyslang')
    ap.add_argument('--sim-vh')
    ap.add_argument('--vmem-ports')
    ap.add_argument('--cache-rows', default='')
    ap.add_argument('--vmem-masters', default='')
    ap.add_argument('--banner', default=BANNER)
    a = ap.parse_args()
    if a.what == 'lift':
        if not (a.srcs and a.out):
            ap.error('lift needs --srcs and --out')
        lift(a)
    else:
        if not (a.sim_vh and a.vmem_ports):
            ap.error('kernel-vh needs --sim-vh and --vmem-ports')
        kernel_vh(a)


if __name__ == '__main__':
    main()
