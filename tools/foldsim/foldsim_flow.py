#!/usr/bin/env python3
"""The design-independent steps of a foldsim image flow, from a target manifest.

  lift         flow/lift_boundaries.py on the design's sources with the
               manifest's [lift] units: the units given plain-port boundaries
               (a module with interface ports becomes a class). Writes
               <out>/srcs.f, the driver's source list.
  kernel-vh    the kernel shell's header for a generated simulator: its memory
               ports, their channel shift and AXI id width, their device-memory
               masters (one per port, or one where the simulator folds its
               ports), the masters' repeat macros (8 a line: Verilator takes at
               most 40000 tokens on a line), the AXI speculation depth, then the
               virtual memories' masters (flow/v80/vmem_ports.py). A simulator
               with static ports (FOLDSIM_VPORTS in foldsim_sim.vh) binds them
               straight to HBM channels, one a port ([platform] hbm_direct, a
               channel list: the flag; without it nothing changes): their
               channels, aperture addresses and repeat macro.
  afu          the kernel's top (rtl/kernel/foldsim_afu.sv.in) with the
               manifest's control binding: [platform.control] names the target
               ports the control endpoint (foldsim_ctrl) drives (reset, start,
               csr_req.valid/rw/addr/data) and reads (csr_rsp.valid/data, busy);
               "!name" binds an active-low port; a role left out is tied off
               (a sink for what the endpoint drives, a constant 0 token for what
               it reads). The endpoint's own names write Vortex's foldsim_afu.sv.
  kernel-srcs  the kernel's source list: the shell (rtl/kernel, or --rtl-dir),
               the simulator, the generated top; for folded memory ports the
               folded endpoint and the threaded one (--threaded: a
               flow/v80/portfold_gen.sh snapshot).
  cfg          the V80 linker config (flow/platform/gen_platform.py): one
               device-memory master per kernel master, the kernel clock; the
               direct static ports m_axi_hbm_<p> on their HBM channels with
               hbm_clk on the static region clock (--hbm-direct).
  ooc-xdc      the kernel clock's constraint for out-of-context synthesis.

The design's own steps (generating its sources: Vortex's gen_sources.sh with its
CONFIGS; its target wrapper, the AXI adapter binding) stay the design's.

usage: foldsim_flow.py lift --manifest <m> --srcs <srcs.f> --out <dir> [--python <pyslang python>]
       foldsim_flow.py kernel-vh --manifest <m> --gen <gen dir> [--cache-rows N] [--vmem-masters N]
       foldsim_flow.py afu --manifest <m> --gen <gen dir> [-o <foldsim_afu.sv>]
       foldsim_flow.py kernel-srcs --gen <gen dir> [--rtl-dir D] [--threaded D] [--afu F] [-o <kernel_srcs.f>]
       foldsim_flow.py cfg --manifest <m> --gen <gen dir> [--freq MHz] [--vmem-masters N] [-o <config.cfg>]
       foldsim_flow.py ooc-xdc --manifest <m> [--freq MHz]
Manifest values may be overridden: --set platform.mem_ports=4 (JSON value).
"""
import argparse
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import foldsim_manifest as fm  # noqa: E402

HERE = os.path.dirname(os.path.realpath(__file__))
FLOW = os.path.join(HERE, 'flow')
# The kernel shell's RTL: beside the tools in a build (bin/../rtl/kernel is not
# installed), else the source tree's rtl/kernel.
RTL_DIRS = [os.path.join(HERE, 'rtl', 'kernel'), os.path.normpath(os.path.join(HERE, '..', '..', 'rtl', 'kernel'))]
BANNER = '// Generated by foldsim_flow.py kernel-vh. Do not edit.'
DEVICE = 'xcv80-lsva4737-2MHP-e-S'

# The control endpoint's roles: (manifest key, foldsim_ctrl port, width, whether
# the endpoint drives it), in the order of foldsim_ctrl's ports.
ROLES = [('reset', 'reset', '1', True),
         ('csr_req.valid', 'dcr_req_valid', '1', True),
         ('csr_req.rw', 'dcr_req_rw', '1', True),
         ('csr_req.addr', 'dcr_req_addr', 'DCR_ADDR_W', True),
         ('csr_req.data', 'dcr_req_data', 'DCR_DATA_W', True),
         ('start', 'start', '1', True),
         ('csr_rsp.valid', 'dcr_rsp_valid', '1', False),
         ('csr_rsp.data', 'dcr_rsp_data', 'DCR_DATA_W', False),
         ('busy', 'busy', '1', False)]


def rtl_dir(a):
    d = a.rtl_dir or next((d for d in RTL_DIRS if os.path.isdir(d)), '')
    if not d:
        sys.exit('foldsim_flow: no rtl/kernel (--rtl-dir)')
    return os.path.abspath(d)


class Manifest:
    def __init__(self, a):
        self.a = a
        self.sets = {}
        for s in getattr(a, 'set', []) or []:
            k, _, v = s.partition('=')
            try:
                v = json.loads(v)
            except ValueError:
                pass
            self.sets[k] = v

    def get(self, key, default=None):
        if key in self.sets:
            return self.sets[key]
        if not self.a.manifest:
            return default
        v = fm.get(self.a.manifest, key, self.a.var)
        return default if v is None else v


def sim_vh(a):
    return os.path.join(a.gen, 'foldsim_sim.vh')


def vmem_ports(a, ports, *extra):
    cmd = [sys.executable, os.path.join(FLOW, 'v80', 'vmem_ports.py'), '--sim-vh', sim_vh(a), '--mem-ports', str(ports)]
    if a.cache_rows:
        cmd += ['--cache-rows', str(a.cache_rows)]
    if a.vmem_masters:
        cmd += ['--vmem-masters', str(a.vmem_masters)]
    return subprocess.run(cmd + list(extra), check=True, text=True, capture_output=True).stdout


def sim_defines(a):
    """foldsim_sim.vh's `define NAME VALUE lines (the last value of a name)."""
    out = {}
    for ln in open(sim_vh(a)):
        mm = re.match(r'\s*`define\s+(\w+)\s*(.*?)\s*(//.*)?$', ln)
        if mm:
            out[mm.group(1)] = mm.group(2)
    return out


# HBM_AXI_<k>'s aperture: a pseudo-channel pair's GiB at 0x40_0000_0000 + (k / 2) GiB
# (the shell's slash_base); the pair's two ports take a half (512 MiB) each.
HBM_BASE = 0x40_0000_0000
VPORT_PARAMS = ('DW', 'MW', 'TW', 'OW', 'LMAX', 'COPY', 'NEED_IN', 'HZ', 'BYTES', 'ZERO', 'FS', 'KS')


def vports(a, m):
    """The simulator's static ports bound to direct HBM channels: [(port, channel, params)], or [] without
    them. The simulator declares them (FOLDSIM_VPORTS P, FOLDSIM_VPORT<p>_<param>); [platform] hbm_direct
    binds each to a channel (no MEM binding of static ports is built)."""
    d = sim_defines(a)
    chans = m.get('platform.hbm_direct')
    if 'FOLDSIM_VPORTS' not in d:
        if chans:
            sys.exit('foldsim_flow: [platform] hbm_direct, and the simulator has no static ports (FOLDSIM_VPORTS)')
        return []
    n = int(d['FOLDSIM_VPORTS'], 0)
    if not isinstance(chans, list) or len(chans) != n:
        sys.exit(f'foldsim_flow: the simulator has {n} static ports: [platform] hbm_direct lists an HBM channel '
                 f'for each (got {chans!r})')
    if len(set(chans)) != n or any(not isinstance(c, int) or not 0 <= c < 64 for c in chans):
        sys.exit(f'foldsim_flow: [platform] hbm_direct {chans}: distinct HBM channels 0-63')
    if n > 64:
        sys.exit(f'foldsim_flow: {n} static ports: at most 64 (one an HBM port)')
    out = []
    for p, k in enumerate(chans):
        pp = {}
        for q in VPORT_PARAMS:
            v = d.get(f'FOLDSIM_VPORT{p}_{q}')
            if v is None:
                sys.exit(f'foldsim_flow: foldsim_sim.vh has no FOLDSIM_VPORT{p}_{q}')
            pp[q] = int(v.replace("'d", '').replace("64'", ''), 0)
        if pp['OW'] + 6 > 29 or pp['BYTES'] > (1 << 29):
            sys.exit(f'foldsim_flow: static port {p}: its region ({pp["BYTES"]} bytes, OW {pp["OW"]}) passes the '
                     '512 MiB of its half of the channel pair')
        out.append((p, k, pp))
    return out


def mem_ports(m):
    ports = m.get('platform.mem_ports')
    if ports not in (1, 2, 4, 8, 16, 32):
        sys.exit(f'foldsim_flow: [platform] mem_ports {ports}: the kernel has 1, 2, 4, 8, 16 or 32 memory ports')
    return ports


def mem_repeat(q, n):
    """FOLDSIM_MEM_REPEAT<q>(f,s): `f(p) for masters 8q..8q+7, joined by `s, a
    part after the first led by `s unless it is empty."""
    xs = ['`f(%d)' % p for p in range(8 * q, min(8 * q + 8, n))]
    return ('`s ' if q and xs else '') + ' `s '.join(xs)


def kernel_vh(a, m):
    ports = mem_ports(m)
    id_w = m.get('platform.mem_id_width')
    if id_w is None:
        sys.exit('kernel-vh: [platform] mem_id_width is the AXI id width of the target\'s memory ports')
    shift = m.get('platform.mem_channel_shift', 0)
    spec = next((v for v in (m.get(f'{s}.axi_spec') for s in ('platform', 'options', 'memory')) if v), 0)
    masters = int(vmem_ports(a, ports, '--port-masters').strip())
    lines = [a.banner, f'`define FOLDSIM_MEM_PORTS {ports}', f'`define FOLDSIM_MEM_CH_SHIFT {shift}',
             f'`define FOLDSIM_MEM_ID_W {id_w}', f'`define FOLDSIM_MEM_MASTERS {masters}']
    lines += [f'`define FOLDSIM_MEM_REPEAT{q}(f,s) {mem_repeat(q, masters)}' for q in range(4)]
    if spec:
        lines.append(f'`define FOLDSIM_MEM_SPEC {spec}')
    vp = vports(a, m)
    if vp:
        # Direct static ports: port p on HBM_AXI_<k>, its region the k's half of the pair's aperture.
        lines += ['`define FOLDSIM_VPORT_DIRECT', f'`define FOLDSIM_VPORT_BYTES {sum(pp["BYTES"] for _, _, pp in vp)}']
        for p, k, _ in vp:
            lines += [f'`define FOLDSIM_VPORT{p}_HBM {k}',
                      f"`define FOLDSIM_VPORT{p}_ADDR 64'h{HBM_BASE + (k >> 1) * (1 << 30) + (k & 1) * (1 << 29):x}"]
        # (8 a line, as the memory ports': at most 64 ports.)
        lines += [f'`define FOLDSIM_VPORT_REPEAT{q}(f,s) {mem_repeat(q, len(vp))}' for q in range(8)]
    return '\n'.join(lines) + '\n' + vmem_ports(a, ports)


def binding(m):
    """[(ctrl port, width, drives, channel name, target port or None, active low)]."""
    ctl = m.get('platform.control')
    if not isinstance(ctl, dict):
        sys.exit('afu: the manifest has no [platform.control] binding (the control endpoint\'s target ports)')
    known = {'reset', 'start', 'busy', 'csr_req', 'csr_rsp', 'csr_addr_width', 'csr_data_width'}
    for k in ctl:
        if k not in known:
            sys.exit(f'afu: [platform.control] {k}: not one of {sorted(known)}')
    out = []
    for key, port, width, drives in ROLES:
        sec, _, field = key.partition('.')
        v = ctl.get(sec)
        if field:
            if v is not None and not isinstance(v, dict):
                sys.exit(f'afu: [platform.control] {sec} is a table of {{valid, ...}}')
            v = (v or {}).get(field)
        if v is not None and not (isinstance(v, str) and re.fullmatch(r'!?[A-Za-z_]\w*', v)):
            sys.exit(f'afu: [platform.control] {key} = {v!r}: a target port name, "!" for active low')
        low = bool(v) and v.startswith('!')
        name = v[1:] if low else v
        if low and width != '1':
            sys.exit(f'afu: [platform.control] {key}: only one-bit roles may be active low')
        chan = name if name and not low else f'foldsim_{"ctl" if name else "nc"}_{port}'
        out.append((port, width, drives, chan, name, low))
    if not any(n for *_, n, _ in out):
        sys.exit('afu: [platform.control] binds no target port')
    return out


def afu(a, m):
    tpl = open(os.path.join(rtl_dir(a), 'foldsim_afu.sv.in')).read()
    tpl = tpl[tpl.index('// Copyright'):]
    bind = binding(m)
    ctl = m.get('platform.control')
    aw, dw = ctl.get('csr_addr_width', 12), ctl.get('csr_data_width', 32)
    # The target's ports as the simulator has them: each bound one's width.
    ports = {p['name']: p['width'] for p in json.load(open(os.path.join(a.gen, 'foldsim_sim.json')))['ports']}
    widths = {'1': 1, 'DCR_ADDR_W': aw, 'DCR_DATA_W': dw}
    chans, ties = [], []
    for port, width, drives, chan, name, low in bind:
        if name:
            if f'{name}_bits' not in ports:
                sys.exit(f'afu: [platform.control] binds {name}, which is no port of the simulator')
            if ports[f'{name}_bits'] != widths[width]:
                sys.exit(f'afu: {name} is {ports[name + "_bits"]} bits, the endpoint\'s {port} {widths[width]}')
            chans.append(f'    `FOLDSIM_CH({name}, {width})')
        if chan != name:
            chans.append(f'    `FOLDSIM_CH({chan}, {width})')
        if name and low:
            src, dst = (chan, name) if drives else (name, chan)
            ties += [f'    assign {dst}_valid = {src}_valid;', f'    assign {src}_ready = {dst}_ready;',
                     f'    assign {dst}_bits = ~{src}_bits;']
        elif not name and drives:
            ties.append(f'    assign {chan}_ready = 1\'b1;')
        elif not name:
            ties += [f'    assign {chan}_valid = 1\'b1;', f'    assign {chan}_bits = \'0;']
    sim = [f'        `FOLDSIM_IN({name})' for _, _, _, _, name, _ in bind if name]
    ctrl = [f'        `FOLDSIM_IN({port})' if chan == port else
            f'        .{port}_valid ({chan}_valid), .{port}_ready ({chan}_ready), .{port}_bits ({chan}_bits)'
            for port, _, _, chan, _, _ in bind]
    join = lambda xs: ',\n'.join(xs)
    s = tpl.replace('@CSR_ADDR_W@', str(aw)).replace('@CSR_DATA_W@', str(dw))
    s = s.replace('@CONTROL_CHANNELS@', '\n'.join(chans + ties))
    s = s.replace('@CONTROL_SIM@', join(sim)).replace('@CONTROL_CTRL@', join(ctrl))
    left = re.findall(r'@[A-Z_]+@', s)
    if left:
        sys.exit(f'afu: template markers left: {left}')
    return s


KERNEL_FILES = ['foldsim_token.sv', 'foldsim_mem_bmap.sv', 'foldsim_mem_bank.sv', 'foldsim_mem.sv',
                'foldsim_vmem.sv', 'foldsim_vmem_share.sv', 'foldsim_vmem_group.sv']


def kernel_srcs(a):
    d = rtl_dir(a)
    gen = os.path.abspath(a.gen)
    folded = re.search(r'^`define FOLDSIM_PORTS ', open(sim_vh(a)).read(), re.M)
    files = [os.path.join(d, f) for f in KERNEL_FILES]
    if folded:
        thr = os.path.join(os.path.abspath(a.threaded or d), 'foldsim_mem_threaded.sv')
        if not os.path.exists(thr):
            sys.exit(f'kernel-srcs: the simulator folds its memory ports, and there is no {thr} (portfold_gen.sh)')
        files += [thr, os.path.join(d, 'foldsim_mem_fold.sv')]
    if re.search(r'^`define FOLDSIM_VPORTS ', open(sim_vh(a)).read(), re.M):
        files.append(os.path.join(d, 'foldsim_vport.sv'))
    files += [os.path.join(d, 'foldsim_ctrl.sv'), os.path.abspath(a.afu or os.path.join(gen, 'foldsim_afu.sv'))]
    return '\n'.join([f'+incdir+{d}', f'+incdir+{gen}', os.path.join(gen, 'foldsim_sim.sv')] + files) + '\n'


def freq(a, m):
    f = a.freq or m.get('platform.clock_mhz')
    if not f:
        sys.exit('foldsim_flow: no kernel clock ([platform] clock_mhz or --freq)')
    return int(f)


def cfg(a, m):
    masters = vmem_ports(a, mem_ports(m), '--masters').strip()
    cmd = [sys.executable, os.path.join(FLOW, 'platform', 'gen_platform.py'), '--flow=aved',
           f'--device={m.get("platform.device", DEVICE)}', '--emit=cfg', '--kernel=foldsim_afu', '--no-host',
           f'--mem-ports={masters}', f'--kernel-mhz={freq(a, m)}']
    vp = vports(a, m)
    if vp:
        cmd.append('--hbm-direct=' + ','.join(str(k) for _, k, _ in vp))
    return subprocess.run(cmd, check=True, text=True, capture_output=True).stdout


def lift(a, m):
    units = m.get('lift.units', [])
    top = m.get('design.top')
    steps = m.get('rtl.max_generate_steps')
    if not top:
        sys.exit('lift: no [design] top in the manifest')
    cmd = [a.python, os.path.join(FLOW, 'lift_boundaries.py'), '--srcs', a.srcs, '--top', top,
           '--out', a.out] + [x for u in units for x in ('--unit', u)]
    if steps:
        cmd += ['--max-generate-steps', str(steps)]
    print('+', ' '.join(cmd), file=sys.stderr)
    sys.exit(subprocess.run(cmd).returncode)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('what', choices=('lift', 'kernel-vh', 'afu', 'kernel-srcs', 'cfg', 'ooc-xdc'))
    ap.add_argument('--manifest', default='')
    ap.add_argument('--var', action='append', default=[], metavar='VAR=VALUE')
    ap.add_argument('--set', action='append', default=[], metavar='SEC.KEY=JSON', help='override a manifest value')
    ap.add_argument('--srcs')
    ap.add_argument('--out')
    ap.add_argument('--python', default=sys.executable, help='lift: a Python with pyslang')
    ap.add_argument('--gen', help="the generation's directory (foldsim_sim.sv/.vh/.json)")
    ap.add_argument('--rtl-dir', default='', help='the kernel shell RTL (default: rtl/kernel)')
    ap.add_argument('--threaded', default='', help='kernel-srcs: the threaded endpoint snapshot (portfold_gen.sh)')
    ap.add_argument('--afu', default='', help='kernel-srcs: the generated top (default <gen>/foldsim_afu.sv)')
    ap.add_argument('--cache-rows', default='')
    ap.add_argument('--vmem-masters', default='')
    ap.add_argument('--freq', type=int, default=0)
    ap.add_argument('--banner', default=BANNER)
    ap.add_argument('-o', '--output', default='-')
    a = ap.parse_args()
    m = Manifest(a)
    if a.what == 'lift':
        if not (a.srcs and a.out):
            ap.error('lift needs --srcs and --out')
        lift(a, m)
    if a.what in ('kernel-vh', 'afu', 'kernel-srcs', 'cfg') and not a.gen:
        ap.error(f'{a.what} needs --gen')
    text = {'kernel-vh': lambda: kernel_vh(a, m), 'afu': lambda: afu(a, m), 'kernel-srcs': lambda: kernel_srcs(a),
            'cfg': lambda: cfg(a, m),
            'ooc-xdc': lambda: 'create_clock -name ap_clk -period %s [get_ports ap_clk]\n'
                               % round(1000 / freq(a, m), 3)}[a.what]()
    if a.output == '-':
        sys.stdout.write(text)
    else:
        os.makedirs(os.path.dirname(os.path.abspath(a.output)), exist_ok=True)
        with open(a.output, 'w') as f:
            f.write(text)


if __name__ == '__main__':
    main()
